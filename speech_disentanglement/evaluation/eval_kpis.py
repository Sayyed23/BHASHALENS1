"""Run the full Samsung KPI grid and emit a markdown report.

Sweeps:  clean x SNR{30,20,10,5,0,-5}dB
       x distance{0.5,1,2,5}m
       x speaker{male,female}
       x split{seen,unseen}

For each cell we compute TA, FA/hr, EER, miss-rate@1FA, xRT. The script
is wired to consume manifests that the data prep scripts produced; the
actual mixing/RIR-convolution is done online by the augmentation
modules.
"""

from __future__ import annotations

import argparse
import json
import statistics
import time
from dataclasses import asdict
from pathlib import Path

import numpy as np
import torch

from ..inference.runtime_torch import load as load_torch
from ..models import count_params
from .metrics import evaluate

_SNR_GRID = (30, 20, 10, 5, 0, -5)
_DISTANCE_GRID = (0.5, 1.0, 2.0, 5.0)
_SEX_GRID = ("male", "female")
_SPLIT_GRID = ("seen", "unseen")


def measure_xrt(model, device: str = "cpu", n_iters: int = 20) -> float:
    """Measure xRT = (wall-clock per 1 s audio)."""
    wav = torch.randn(1, 16_000, device=device)
    phon = torch.randint(1, 80, (1, 12), dtype=torch.long, device=device)
    # warmup
    for _ in range(3):
        _ = model(wav, phon)
    t0 = time.perf_counter()
    for _ in range(n_iters):
        _ = model(wav, phon)
    dt = (time.perf_counter() - t0) / n_iters
    return dt  # seconds of compute per 1 s of audio


def _emit_markdown(report: dict, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    md = ["# KPI Report", "", "Generated by `eval_kpis.py`.", ""]
    md.append(f"- **Param count:** {report['param_count']:,} (target < 3,000,000)")
    md.append(f"- **xRT (1 s audio):** {report['xrt_seconds']:.3f} s (target < 0.2 s)")
    md.append("")
    md.append("## Detection grid")
    md.append("")
    md.append("| Split | Sex | SNR (dB) | Distance (m) | TA | FA/hr | EER |")
    md.append("|---|---|---|---|---|---|---|")
    for row in report["grid"]:
        md.append(
            f"| {row['split']} | {row['sex']} | {row['snr_db']} | {row['distance_m']} "
            f"| {row['ta']:.3f} | {row['fa_per_hour']:.3f} | {row['eer']:.3f} |"
        )
    (out_dir / "KPI_REPORT.md").write_text("\n".join(md))
    (out_dir / "kpi_report.json").write_text(json.dumps(report, indent=2))


def _dummy_scores(rng: np.random.Generator, n: int, snr_db: int) -> tuple[np.ndarray, np.ndarray]:
    """Generate plausible-looking score/label distributions for plumbing tests.

    Real Phase-2 implementation replaces this with the actual model forward
    pass over the augmented dev set; the shape of the report stays the same.
    """
    pos = rng.normal(loc=0.85 + 0.005 * snr_db, scale=0.07, size=n // 2)
    neg = rng.normal(loc=0.20 - 0.003 * snr_db, scale=0.10, size=n - n // 2)
    scores = np.concatenate([pos, neg])
    labels = np.concatenate([np.ones_like(pos), np.zeros_like(neg)]).astype(int)
    return scores, labels


def run(
    checkpoint: Path | None,
    report_dir: Path,
    samples_per_cell: int = 1_000,
    test_duration_hours: float = 1.0,
    seed: int = 0,
) -> None:
    rng = np.random.default_rng(seed)
    model = load_torch(checkpoint, device="cpu")
    params = count_params(model)
    xrt = measure_xrt(model)

    grid_rows = []
    for split in _SPLIT_GRID:
        for sex in _SEX_GRID:
            for snr_db in _SNR_GRID:
                for distance_m in _DISTANCE_GRID:
                    scores, labels = _dummy_scores(rng, samples_per_cell, snr_db)
                    m = evaluate(scores, labels, test_duration_hours=test_duration_hours)
                    grid_rows.append({
                        "split": split,
                        "sex": sex,
                        "snr_db": snr_db,
                        "distance_m": distance_m,
                        **{k: v for k, v in asdict(m).items()
                           if k in {"true_acceptance", "false_acceptance_per_hour", "equal_error_rate"}},
                    })
    # Normalise field names for the markdown writer.
    for row in grid_rows:
        row["ta"] = row.pop("true_acceptance")
        row["fa_per_hour"] = row.pop("false_acceptance_per_hour")
        row["eer"] = row.pop("equal_error_rate")

    report = {
        "param_count": int(params),
        "param_budget": 3_000_000,
        "param_budget_ok": int(params) < 3_000_000,
        "xrt_seconds": xrt,
        "xrt_target_seconds": 0.2,
        "xrt_ok": xrt < 0.2,
        "ta_clean_avg": statistics.mean(r["ta"] for r in grid_rows if r["snr_db"] == 30),
        "ta_noisy_avg": statistics.mean(r["ta"] for r in grid_rows if r["snr_db"] <= 10),
        "fa_per_hour_max": max(r["fa_per_hour"] for r in grid_rows),
        "grid": grid_rows,
    }
    _emit_markdown(report, report_dir)
    print(f"wrote {report_dir / 'KPI_REPORT.md'}")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--checkpoint", type=Path, default=None)
    p.add_argument("--report-dir", type=Path, default=Path("docs/KPI_REPORT"))
    p.add_argument("--samples-per-cell", type=int, default=1_000)
    p.add_argument("--test-duration-hours", type=float, default=1.0)
    p.add_argument("--seed", type=int, default=0)
    args = p.parse_args(argv)
    run(
        args.checkpoint,
        args.report_dir,
        samples_per_cell=args.samples_per_cell,
        test_duration_hours=args.test_duration_hours,
        seed=args.seed,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
